#!/usr/bin/env python3
"""goal_tasks.py -- project registry goals into Harness^2 tasks.

Only goals whose criterion names a runnable command become tasks. A check that
cannot fail (`true`, `:`) is refused: a probe scored by it would always "pass"
and teach the loop nothing.

Usage:
  python3 tools/goal_tasks.py --registry docs/GOALS-1000.json --out docs/tasks/goals.json
  python3 tools/goal_tasks.py --self-test
"""
from __future__ import annotations

import argparse
import json
import re
import sys

CMD = re.compile(r"`([^`]+)`")
# Criteria are written as prose: "make test_X: ..." appears unbackticked too.
BARE = re.compile(r"\b(make\s+[A-Za-z0-9_./-]+|python3\s+[A-Za-z0-9_./-]+)")
REPOS = {"wubunos": "/home/wubu/wubunos", "wubuos": "/home/wubu/wubuos",
         "wubuwizard": "/home/wubu/wubuwizard"}
UNFALSIFIABLE = {"true", ":", "exit 0", "/bin/true"}


def project(goals: list[dict]) -> list[dict]:
    out = []
    for g in goals:
        crit = g.get("criterion", "")
        # A criterion that names a test target means "make that target".
        tgts = re.findall(r"\b(test_[A-Za-z0-9_]+|check_[A-Za-z0-9_]+|gauntlet_[A-Za-z0-9_]+)\b", crit)
        cmds = [c.strip() for c in CMD.findall(crit)]
        cmds += [m.group(1).strip() for m in BARE.finditer(crit)]
        cmds = [c for c in cmds if c.split(" ")[1:2] not in (["target"], ["sure"], [])]
        cmd = f"make {tgts[0]}" if tgts else next(
            (c for c in cmds if c.split(" ")[0] in ("make", "python3", "sh", "./")), None)
        if not cmd or cmd in UNFALSIFIABLE:
            continue
        cwd = next((p for r, p in REPOS.items() if r in (g.get("module", "") + crit)), None)
        if not cwd:
            continue
        out.append({
            "id": f"goal-{g['n']}",
            "prompt": f"Goal {g['n']} ({g.get('domain','?')}): {g.get('title','').strip()}\n"
                      f"Acceptance: {crit.strip()}",
            "check": cmd,
            "cwd": cwd,
        })
    return out


def self_test() -> int:
    fails = 0

    def check(cond, label):
        nonlocal fails
        print(("PASS  " if cond else "FAIL  ") + label)
        fails += 0 if cond else 1

    goals = [
        {"n": 1, "domain": "COMPILER", "title": "battery", "module": "wubunos/x.c",
         "criterion": "`make test_mir_battery` prints WRONG: 0"},
        {"n": 2, "domain": "UX", "title": "vibes", "module": "wubuos/x.c",
         "criterion": "the design is elegant"},
        {"n": 3, "domain": "STACK", "title": "fake", "module": "wubuwizard/x.c",
         "criterion": "`true` always"},
        {"n": 4, "domain": "BRAIN", "title": "py", "module": "wubuwizard/tools/x.py",
         "criterion": "`python3 tools/check.py` exits 0"},
    ]
    tasks = project(goals)
    ids = [t["id"] for t in tasks]
    check(ids == ["goal-1", "goal-4"], "keeps only goals with a runnable, falsifiable command")
    check(tasks[0]["check"] == "make test_mir_battery", "extracts the exact command")
    check(tasks[0]["cwd"] == "/home/wubu/wubunos", "maps the repo to its root")
    check(all(t["prompt"] and t["check"] for t in tasks), "every task has a prompt and a check")
    print("ALL PASSED" if fails == 0 else f"{fails} FAILURES")
    return 0 if fails == 0 else 1


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--registry", default="docs/GOALS-1000.json")
    ap.add_argument("--out", default="docs/tasks/goals.json")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test()

    data = json.load(open(a.registry))
    goals = data["goals"] if isinstance(data, dict) else data
    tasks = project(goals)
    if not tasks:
        print("no projectable goals: every criterion was prose or an unfalsifiable check")
        return 1
    import os
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    json.dump({"note": "generated by tools/goal_tasks.py from the registry",
               "tasks": tasks}, open(a.out, "w"), indent=1)
    print(f"wrote {len(tasks)} task(s) to {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())